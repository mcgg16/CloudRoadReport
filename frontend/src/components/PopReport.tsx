import { useEffect, useState } from 'react';
import type { Conditions, Names } from '../types/types';

type OpenPopReportState = {
    open: boolean;
    onClose: () => void;
}

function PopReport({ open, onClose }: OpenPopReportState) {
    const [loading, setLoading] = useState(false);
    const [regions, setRegions] = useState<Names[]>([]); // Stores the regions for dropdown
    const [regionId, setRegionId] = useState(''); // Region selected for submit
    const [conditions, setConditions] = useState<Conditions[]>([]); // To show buttons w name and mini description for standarizing
    const [conditionId, setConditionId] = useState(1); // Default sets it to dry condition, let the user pick a new one
    const [errorMessage, setErrorMessage] = useState('');

    // Gets current time for report, generated by AI to use brisbane time zones
    function getCurrentTime() {
        // Sets timezone to australia and applies formatting
        const parts = new Intl.DateTimeFormat('en-AU', {
            timeZone: 'Australia/Brisbane',
            hour: '2-digit',
            minute: '2-digit',
            hourCycle: 'h23',
        }).formatToParts(new Date());

        const hour = parts.find((part) => part.type === 'hour')?.value ?? '00';
        const minute = parts.find((part) => part.type === 'minute')?.value ?? '00';

        return `${hour}:${minute}`;
    }

    const [observeTime, setObserveTime] = useState(getCurrentTime);

    // Get regions
    useEffect(() => {
        if (!open) {
            return;
        }

        let ignore = false;

        // Uses here the flask api route to fetch the region reports
        async function loadRegionNames() {
            try {
                setLoading(true);

                const response = await fetch('/api/reports/names');

                // Error loadign region
                if (!response.ok) {
                    throw new Error(`Could not load region names (${response.status})`);
                }

                // Recieves data 
                const data: Names[] = await response.json();

                if (!ignore) {
                    // Tries to establish the regions that should have been obtained 
                    setRegions(data);
                }
            } catch (error) {
                if (!ignore) {
                    // So it did get the request but could not set them 
                    console.log('Could not get region names');
                }
            } finally {
                // Did work, so finished loading 
                if (!ignore) {
                    setLoading(false);
                }
            }
        }

        // Calll funct to load regions 
        loadRegionNames();

        return () => {
            ignore = true;
        };
    }, [open]); // Sets to true to load it, otherwise didn't even show it up

    // Get conditions for label
    useEffect(() => {
        if (!open) {
            return;
        }

        let ignore = false;

        // Uses here the flask api route to fetch the region reports
        async function loadConditions() {
            try {
                setLoading(true);

                const response = await fetch('/api/reports/conditions');

                // Error loadign region
                if (!response.ok) {
                    throw new Error(`Could not load condition names and labels (${response.status})`);
                }

                // Recieves data 
                const data: Conditions[] = await response.json();

                if (!ignore) {
                    // Tries to establish the regions that should have been obtained 
                    setConditions(data);
                }
            } catch (error) {
                if (!ignore) {
                    // So it did get the request but could not set them 
                    console.log('Could not get condition options');
                }
            } finally {
                // Did work, so finished loading 
                if (!ignore) {
                    setLoading(false);
                }
            }
        }

        // Calll funct to load regions 
        loadConditions();

        return () => {
            ignore = true;
        };
    }, [open]);

    // Not opened, doesn't return anything
    if (!open) {
        return null;
    }

    // Submit the report 
    async function submitReport() {
        console.log("Handle the click");
        setErrorMessage('');

        // Check information 
        if (regionId === '') {
            // No region selected
            setErrorMessage("Please select a region")
        }
        else if (observeTime > getCurrentTime()) {
            // Selecting time in the future 
            setErrorMessage("Cannot set observation to a future time");
        } else {
            // Shows that it is going to load
            setLoading(true);

            // Sends the query 
            try {
                // AI correction asking for revision for window reloading it let me know that I needed to assign regionId as Number(regionId)
                const response = await fetch('/api/reports/make', {
                    method: 'POST',
                    headers: {
                        'Content-Type': 'application/json',
                    },
                    body: JSON.stringify({
                        observeTime,
                        conditionId,
                        regionId: Number(regionId),
                    }),
                });

                // Waits to see what endpoint says
                const data = await response.json();

                // Something died
                if (!response.ok) {
                    throw new Error(data.error || 'Could not create report');
                }

                console.log('Created report');
                open = false; // Sets to false to close pop-up if it was succesful
                window.location.assign('/');// AI suggestion, I had navigate('/') but apparently this is better to full reload the home page; prompt "instead of navigate i want to make it so that it uses location to detect that a new report was submitted and "force reload" home... and id appreciate a revision... but keep it as simple as possible with minor code changes"
            } catch (error) {
                console.log('Error ', error);
                setErrorMessage('Could not make report, please try again later');
            } finally {
                setLoading(false);
            }
        }
    }

    return (
        <div className="fixed inset-0 z-50 flex items-center justify-center p-4">
            <div
                className="absolute inset-0 bg-black/40"
                onClick={onClose}
            />

            <div className="relative w-100 z-10 bg-white rounded-2xl p-6">
                <div className="flex justify-between gap-8">
                    <h2 className="text-lg font-bold">Submit a Report</h2>

                    {/* Close pop-up */}
                    <button
                        type="button"
                        onClick={onClose}
                        className="text-xl text-gray-600 hover:text-gray-400"
                    >x</button>
                </div>

                {/* Rest of pop-up body fields and button */}
                <div className="flex flex-col items-center text-center">
                    {/* All the data fields */}
                    <div className="flex flex-col items-center justify-center py-2 my-2">
                        {/* Region */}
                        <div>
                            <h3 className="text-lg font-semibold">Region</h3>

                            {/* Dropdown generated by ChatGPT because there were too many different approaches and I wanted something fast and personalized to the effect I defined; uses the region variable w value of regionId, when different one is selected update the id. Maps over regions to generate the list dropped down */}
                            <select
                                id="region"
                                value={regionId}
                                onChange={(e) => setRegionId(e.target.value)}
                                required
                                className="h-11 px-4 bg-gray-100 rounded-2xl"
                            >
                                <option value="" disabled>Select a region</option>

                                {regions.map((region) => (
                                    <option key={region.id} value={region.id}>
                                        {region.name}
                                    </option>
                                ))}
                            </select>
                        </div>

                        {/* Condition with description */}
                        <div>
                            <h3 className="text-lg font-semibold mt-3">Select road condition</h3>
                            {/* Map over conditions  to generate the buttons */}
                            <div className="grid grid-cols-2 gap-3 mt-2">
                                {conditions.map((condition) => (
                                    // Note the button checks the selected conditionId matches the conditions mapping object created to load the name and desc
                                    <button
                                        key={condition.id}
                                        type="button"
                                        onClick={() => setConditionId(condition.id)}
                                        className={`rounded-2xl text-center px-2 py-2 ${conditionId == condition.id ? 'bg-blue-300' : 'bg-gray-100 hover:bg-gray-400'}`}
                                    >
                                        <p className="font-bold">{condition.name}</p>

                                        <p className="mt-1 text-sm text-black">{condition.description}</p>
                                    </button>
                                ))}
                            </div>
                        </div>

                        {/* Time column */}
                        <div>
                            <h3 className="text-lg font-semibold mt-3">Time of observation</h3>
                            <div className="flex flex-row">
                                <input
                                    name="time"
                                    type="time"
                                    value={observeTime}
                                    onChange={(event) => setObserveTime(event.target.value)}
                                    placeholder="--:-- ----"
                                    className="h-11 px-4 bg-gray-100 rounded-2xl"
                                />
                            </div>
                        </div>
                    </div>

                    {/* Submit and close */}
                    <button
                        type="button"
                        onClick={submitReport}
                        disabled={loading}
                        className="mt-2 text-white font-bold bg-blue-400 hover:bg-blue-700 py-2 px-8 py-6 rounded-2xl disabled:opacity-50"
                    >
                        {loading ? 'Submitting...' : 'Submit'}
                    </button>

                    {/* Had an error */}
                    {errorMessage && <p className="text-center rounded-lg bg-red-100 text-red-800 outline-2 outline-red-800 mt-2 mb-1 px-2 py-3">{errorMessage}</p>}
                </div>

            </div>
        </div>
    )
}

export default PopReport;