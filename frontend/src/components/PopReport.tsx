import { useEffect, useState } from 'react';
import type { Conditions, Names } from '../types/types';

type OpenPopReportState = {
    open: boolean;
    onClose: () => void;
}

function PopReport({ open, onClose }: OpenPopReportState) {
    const [loading, setLoading] = useState(false);
    const [regions, setRegions] = useState<Names[]>([]); // Stores the regions for dropdown
    const [regionId, setRegionId] = useState(''); // Region selected for submit

    // Get regions
    useEffect(() => {
        if (!open) {
            return;
        }

        let ignore = false;

        // Uses here the flask api route to fetch the region reports
        async function loadRegionNames() {
            try {
                setLoading(true);

                const response = await fetch('/api/reports/names');

                // Error loadign region
                if (!response.ok) {
                    throw new Error(`Could not load region names (${response.status})`);
                }

                // Recieves data 
                const data: Names[] = await response.json();

                if (!ignore) {
                    // Tries to establish the regions that should have been obtained 
                    setRegions(data);
                }
            } catch (error) {
                if (!ignore) {
                    // So it did get the request but could not set them 
                    console.log('Could not get region names');
                }
            } finally {
                // Did work, so finished loading 
                if (!ignore) {
                    setLoading(false);
                }
            }
        }

        // Calll funct to load regions 
        loadRegionNames();

        return () => {
            ignore = true;
        };
    }, [open]); // Sets to true to load it, otherwise didn't even show it up

    // Get conditions for label

    // Not opened, doesn't return anything
    if (!open) {
        return null;
    }

    // Submit the report 
    async function submitReport() {
        // Nothing for now, will be the one making call to API
    }

    return (
        <div className="fixed inset-0 z-50 flex items-center justify-center p-4">
            <div
                className="absolute inset-0 bg-black/40"
                onClick={onClose}
            />

            <div className="relative w-100 z-10 bg-white rounded-2xl p-6">
                <div className="flex justify-between gap-8">
                    <h2 className="text-lg font-bold">Submit a Report</h2>

                    {/* Close pop-up */}
                    <button
                        type="button"
                        onClick={onClose}
                        className="text-xl text-gray-600 hover:text-gray-400"
                    >
                        x
                    </button>
                </div>

                {/* Rest of pop-up body fields and button */}
                <div className="flex flex-col items-center text-center">
                    {/* All the data fields */}
                    <div className="flex flex-col items-center justify-center py-2 my-2">
                        {/* Region */}
                        <div>
                            <h3 className="text-lg font-semibold">Region</h3>
                            <p>Select the region to report</p>

                            {/* Dropdown generated by ChatGPT because there were too many different approaches and I wanted something fast and personalized to the effect I defined; uses the region variable w value of regionId, when different one is selected update the id. Maps over regions to generate the list dropped down */}
                            <select
                                id="region"
                                value={regionId}
                                onChange={(e) => setRegionId(e.target.value)}
                                required
                                className="h-11 px-4 bg-gray-100 rounded-2xl"
                            >
                                <option value="" disabled>Select a region</option>

                                {regions.map((region) => (
                                    <option key={region.id} value={region.id}>
                                        {region.name}
                                    </option>
                                ))}
                            </select>
                        </div>

                        {/* Condition with description */}
                        <div>
                            <h3 className="text-lg font-semibold mt-3">Select road condition</h3>
                            <div className="grid grid-cols-2">
                                <div>
                                    <p>1</p>
                                    <p>2</p>
                                </div>
                                <div>
                                    <p>3</p>
                                    <p>4</p>
                                </div>
                            </div>

                        </div>

                        {/* Time column */}
                        <div>
                            <h3 className="text-lg font-semibold mt-3">Time of observation</h3>
                            <div className="flex flex-row">
                                <p>Hour</p>
                                <p>Minutes</p>
                                <p>am/pm</p>
                            </div>
                        </div>
                    </div>


                    {/* Close the pop-up */}
                    <button
                        type="button"
                        onClick={submitReport}
                        disabled={loading}
                        className="mt-6 text-white font-bold bg-blue-400 hover:bg-blue-700 py-2 px-4 rounded-2xl disabled:opacity-50"
                    >
                        {loading ? 'Submitting...' : 'Submit'}
                    </button>
                </div>

            </div>
        </div>
    )
}

export default PopReport;